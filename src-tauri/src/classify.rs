//! Classify an inbound mail as auto-reply, bounce, or human reply.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ReplyKind {
    Auto,
    Human,
    Bounce,
}

impl ReplyKind {
    pub fn as_str(self) -> &'static str {
        match self {
            ReplyKind::Auto => "auto",
            ReplyKind::Human => "human",
            ReplyKind::Bounce => "bounce",
        }
    }
}

#[derive(Debug, Clone, Default)]
pub struct IncomingMail {
    pub from: String,
    pub subject: String,
    pub body: String,
    pub auto_submitted: String,
    pub precedence: String,
    pub content_type: String,
    pub extra_headers: Vec<(String, String)>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Classification {
    pub kind: ReplyKind,
    pub reason: String,
}

pub fn classify(mail: &IncomingMail) -> Classification {
    let from = mail.from.to_lowercase();
    let subject = mail.subject.to_lowercase();
    let body = unique_body(&mail.body);
    let body_l = body.to_lowercase();
    let auto_submitted = mail.auto_submitted.to_lowercase();
    let precedence = mail.precedence.to_lowercase();
    let content_type = mail.content_type.to_lowercase();
    let headers = mail
        .extra_headers
        .iter()
        .map(|(k, v)| (k.to_lowercase(), v.to_lowercase()))
        .collect::<Vec<_>>();

    if is_bounce(&from, &subject, &body_l, &content_type, &headers) {
        return Classification {
            kind: ReplyKind::Bounce,
            reason: "退信或投递失败通知".into(),
        };
    }

    let mut auto = 0i32;
    let mut reasons: Vec<&str> = Vec::new();

    if auto_submitted.contains("auto-replied") || auto_submitted.contains("auto-generated") {
        auto += 6;
        reasons.push("邮件头 Auto-Submitted");
    }
    if precedence.contains("auto") || precedence.contains("bulk") || precedence.contains("junk") {
        auto += 3;
        reasons.push("邮件头 Precedence");
    }
    if header_present(&headers, "x-autoreply")
        || header_present(&headers, "x-auto-reply")
        || header_present(&headers, "x-autogenerated")
        || header_present(&headers, "x-autoreply")
    {
        auto += 5;
        reasons.push("自动回复专用头");
    }
    if is_noreply_from(&from) {
        auto += 4;
        reasons.push("发件人是系统地址");
    }
    if subject_is_auto(&subject) {
        auto += 4;
        reasons.push("主题像自动回复");
    }
    if body_is_auto(&body_l) {
        auto += 3;
        reasons.push("正文像自动回复");
    }

    let mut human = 0i32;
    if body.chars().count() >= 80 {
        human += 2;
    }
    if body_is_editorial(&body_l) {
        human += 4;
    }
    if auto_submitted.trim() == "no" {
        human += 2;
    }

    if auto >= 3 && auto >= human {
        let reason = if reasons.is_empty() {
            "综合判定为自动回复".into()
        } else {
            format!("判定为自动回复：{}", reasons.join("、"))
        };
        return Classification {
            kind: ReplyKind::Auto,
            reason,
        };
    }

    Classification {
        kind: ReplyKind::Human,
        reason: if body_is_editorial(&body_l) {
            "正文像编辑人工回复".into()
        } else if auto == 0 {
            "没有自动回复特征，按人工回复处理".into()
        } else {
            "自动回复特征不足，按人工回复处理".into()
        },
    }
}

fn header_present(headers: &[(String, String)], name: &str) -> bool {
    headers.iter().any(|(k, v)| k == name && v != "no" && !v.is_empty())
}

fn is_noreply_from(from: &str) -> bool {
    const MARKERS: &[&str] = &[
        "mailer-daemon",
        "postmaster",
        "no-reply",
        "noreply",
        "donotreply",
        "do-not-reply",
        "autoreply",
        "auto-reply",
        "autoresponder",
        "bounce",
        "mailerdaemon",
    ];
    MARKERS.iter().any(|m| from.contains(m))
}

fn is_bounce(
    from: &str,
    subject: &str,
    body: &str,
    content_type: &str,
    headers: &[(String, String)],
) -> bool {
    if content_type.contains("multipart/report") || content_type.contains("delivery-status") {
        return true;
    }
    if header_present(headers, "x-failed-recipients") {
        return true;
    }
    if from.contains("mailer-daemon") || from.contains("postmaster") {
        return true;
    }
    const SUBJ: &[&str] = &[
        "undeliverable",
        "undelivered",
        "delivery status",
        "delivery failure",
        "returned mail",
        "mail delivery failed",
        "failure notice",
        "无法投递",
        "投递失败",
        "退信",
        "退回",
        "地址不存在",
    ];
    SUBJ.iter().any(|k| subject.contains(k)) || body.contains("diagnostic-code")
}

