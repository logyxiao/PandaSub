fn unique_body(body: &str) -> String {
    let mut lines = Vec::new();
    for line in body.lines() {
        let t = line.trim();
        if t.starts_with('>') {
            continue;
        }
        if t.starts_with("On ") && t.contains("wrote") {
            break;
        }
        if t.contains("原始邮件") || t.contains("Original Message") || t.contains("转发的邮件") {
            break;
        }
        if t.starts_with("-----") {
            break;
        }
        if t.starts_with("在 ") && (t.contains("写道") || t.contains("寫道")) {
            break;
        }
        lines.push(t);
    }
    lines.join("\n").trim().to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn mail(from: &str, subject: &str, body: &str) -> IncomingMail {
        IncomingMail {
            from: from.into(),
            subject: subject.into(),
            body: body.into(),
            ..IncomingMail::default()
        }
    }

    #[test]
    fn auto_submitted_header() {
        let mut m = mail("editor@site.com", "Re: 投石穿云", "已收到");
        m.auto_submitted = "auto-replied".into();
        assert_eq!(classify(&m).kind, ReplyKind::Auto);
    }

    #[test]
    fn chinese_auto_subject() {
        let m = mail("noreply@site.com", "自动回复：已收到投稿", "请勿回复此邮件，这是系统自动发送的。");
        assert_eq!(classify(&m).kind, ReplyKind::Auto);
    }

    #[test]
    fn editorial_human() {
        let m = mail(
            "zhangsan@qidian.com",
            "Re: 投石穿云",
            "您好，责编看过第一章，建议修改开篇节奏，进入二审前请先按意见改一版。",
        );
        assert_eq!(classify(&m).kind, ReplyKind::Human);
    }

    #[test]
    fn bounce_mailer_daemon() {
        let m = mail("MAILER-DAEMON@qq.com", "Undelivered Mail Returned to Sender", "Diagnostic-Code: smtp; 550");
        assert_eq!(classify(&m).kind, ReplyKind::Bounce);
    }

    #[test]
    fn received_manuscript_auto() {
        let m = mail(
            "tougao@web.com",
            "投稿确认",
            "感谢您的投稿，稿件已进入审核队列。此邮件由系统发出，请勿回复。",
        );
        assert_eq!(classify(&m).kind, ReplyKind::Auto);
    }

    #[test]
    fn short_plain_reply_is_human() {
        let m = mail("editor@site.com", "Re: 投石穿云", "方便今晚十点通话吗？我是责编李四。");
        assert_eq!(classify(&m).kind, ReplyKind::Human);
    }
}
